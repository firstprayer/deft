//! Writes THIRD-PARTY-NOTICES.md: the license text of every crate linked into
//! the `deft` binary. Permissive licenses require these notices to travel with
//! the program.

use crate::root;
use serde_json::Value;
use std::collections::{BTreeMap, HashMap, HashSet};
use std::fmt::Write as _;
use std::path::Path;
use std::process::Command;

const FONTS: &str = "Fonts embedded through typst-assets: Libertinus Serif (SIL Open Font License 1.1), New Computer Modern (GUST Font License), DejaVu Sans Mono (Bitstream Vera and Arev licenses).";

fn license_files(dir: &Path) -> Vec<String> {
    let mut texts = Vec::new();
    let Ok(entries) = std::fs::read_dir(dir) else {
        return texts;
    };
    let mut names: Vec<_> = entries
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.is_file())
        .collect();
    names.sort();
    for p in names {
        let name = p
            .file_name()
            .map(|n| n.to_string_lossy().to_ascii_uppercase())
            .unwrap_or_default();
        if ["LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE"]
            .iter()
            .any(|k| name.starts_with(k))
            && let Ok(t) = std::fs::read_to_string(&p)
        {
            texts.push(t.trim().to_string());
        }
    }
    texts
}

pub fn write() -> Result<(), String> {
    let out = Command::new("cargo")
        .args(["metadata", "--format-version", "1", "--locked"])
        .current_dir(root())
        .output()
        .map_err(|e| e.to_string())?;
    let meta: Value = serde_json::from_slice(&out.stdout).map_err(|e| e.to_string())?;
    let packages: HashMap<&str, &Value> = meta["packages"]
        .as_array()
        .ok_or("no packages")?
        .iter()
        .filter_map(|p| Some((p["id"].as_str()?, p)))
        .collect();
    let members: HashSet<&str> = meta["workspace_members"]
        .as_array()
        .ok_or("no members")?
        .iter()
        .filter_map(Value::as_str)
        .collect();
    let nodes: HashMap<&str, &Value> = meta["resolve"]["nodes"]
        .as_array()
        .ok_or("no graph")?
        .iter()
        .filter_map(|n| Some((n["id"].as_str()?, n)))
        .collect();
    let start = packages
        .iter()
        .find(|(_, p)| p["name"] == "deftcli")
        .map(|(id, _)| *id)
        .ok_or("deftcli not found")?;
    // Follow normal dependencies only: what actually ends up in the binary.
    let (mut seen, mut stack) = (HashSet::new(), vec![start]);
    while let Some(id) = stack.pop() {
        if !seen.insert(id) {
            continue;
        }
        for d in nodes[id]["deps"].as_array().into_iter().flatten() {
            let normal = d["dep_kinds"]
                .as_array()
                .into_iter()
                .flatten()
                .any(|k| k["kind"].is_null());
            if normal {
                stack.extend(d["pkg"].as_str());
            }
        }
    }
    // Group crates that share identical license text.
    let mut by_text: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut table = Vec::new();
    let mut missing = Vec::new();
    for id in seen.iter().filter(|id| !members.contains(*id)) {
        let p = packages[id];
        let label = format!(
            "{} {}",
            p["name"].as_str().unwrap_or(""),
            p["version"].as_str().unwrap_or("")
        );
        table.push((
            label.clone(),
            p["license"].as_str().unwrap_or("unknown").to_string(),
        ));
        let dir = Path::new(p["manifest_path"].as_str().unwrap_or(""))
            .parent()
            .map(Path::to_path_buf)
            .unwrap_or_default();
        let texts = license_files(&dir);
        if texts.is_empty() {
            missing.push(label.clone());
        }
        for t in texts {
            by_text.entry(t).or_default().push(label.clone());
        }
    }
    table.sort();
    let mut s = String::from(
        "# Third-party notices\n\nGenerated by `cargo xtask notices`; do not edit.\n\nDeft is licensed under the PolyForm Shield License 1.0.0 (see LICENSE.md). The components below keep their own licenses.\n\n",
    );
    let _ = writeln!(
        s,
        "{FONTS}\n\nExternal programs such as ffmpeg and yt-dlp are not part of Deft; they keep their own licenses.\n\n## Components\n\n| Crate | License |\n|---|---|"
    );
    for (name, license) in &table {
        let _ = writeln!(s, "| {name} | {license} |");
    }
    s.push_str("\n## License texts\n");
    for (text, mut crates) in by_text {
        crates.sort();
        let _ = write!(s, "\n### {}\n\n```text\n{text}\n```\n", crates.join(", "));
    }
    if !missing.is_empty() {
        missing.sort();
        let _ = write!(
            s,
            "\n## Crates that ship no license file\n\nThese are covered by the license named in the table above.\n\n{}\n",
            missing
                .iter()
                .map(|m| format!("- {m}"))
                .collect::<Vec<_>>()
                .join("\n")
        );
    }
    std::fs::write(root().join("THIRD-PARTY-NOTICES.md"), &s).map_err(|e| e.to_string())?;
    println!(
        "{} crates, {} license texts, {} without a license file, {} KB",
        table.len(),
        s.matches("```text").count(),
        missing.len(),
        s.len() / 1024
    );
    Ok(())
}
