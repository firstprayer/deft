//! Generates the operation registry from the directory layout:
//!
//!   src/ops/<group>/_group.rs   -> `pub static GROUP: Group`
//!   src/ops/<group>/<name>.rs   -> `pub static OP: Op`   (one operation)
//!   src/ops/<group>/_<name>.rs  -> helper module shared inside the group
//!
//! Adding a file or a directory is enough; no existing file is edited.

use std::fmt::Write as _;
use std::path::Path;

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("src/ops");
    println!("cargo:rerun-if-changed={}", root.display());
    let mut groups: Vec<_> = std::fs::read_dir(&root)
        .expect("src/ops exists")
        .filter_map(|e| e.ok())
        .filter(|e| e.path().is_dir() && e.path().join("_group.rs").exists())
        .map(|e| e.path())
        .collect();
    groups.sort();

    let mut modules = String::new();
    let mut group_list = String::new();
    let mut op_list = String::new();
    let mut sources = String::new();
    for dir in &groups {
        println!("cargo:rerun-if-changed={}", dir.display());
        let group = dir.file_name().unwrap().to_str().unwrap().to_string();
        let feature_gate = feature_for(&group);
        let mut files: Vec<_> = std::fs::read_dir(dir)
            .unwrap()
            .filter_map(|e| e.ok())
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|x| x == "rs"))
            .collect();
        files.sort();
        let cfg = feature_gate
            .map(|f| format!("#[cfg(feature = \"{f}\")] "))
            .unwrap_or_default();
        writeln!(modules, "{cfg}pub mod {group} {{").unwrap();
        for file in &files {
            println!("cargo:rerun-if-changed={}", file.display());
            let name = file.file_stem().unwrap().to_str().unwrap();
            writeln!(
                modules,
                "    #[path = {:?}] pub mod {name};",
                file.display().to_string()
            )
            .unwrap();
            if name == "_group" {
                writeln!(group_list, "    {cfg}&{group}::_group::GROUP,").unwrap();
            } else if !name.starts_with('_') {
                writeln!(op_list, "    {cfg}&{group}::{name}::OP,").unwrap();
                writeln!(
                    sources,
                    "    {cfg}({group:?}, {name:?}, &{group}::{name}::OP),"
                )
                .unwrap();
            }
        }
        writeln!(modules, "}}").unwrap();
    }

    let code = format!(
        "// @generated by build.rs from src/ops. Do not edit.\n{modules}\n\
         /// Every group, in directory order.\npub static GROUPS: &[&deft_core::spec::Group] = &[\n{group_list}];\n\
         /// Every operation, in directory order.\npub static OPS: &[&deft_core::spec::Op] = &[\n{op_list}];\n\
         /// (directory, file stem, operation) for the contract tests.\npub static SOURCES: &[(&str, &str, &deft_core::spec::Op)] = &[\n{sources}];\n"
    );
    let out = Path::new(&std::env::var("OUT_DIR").unwrap()).join("registry_gen.rs");
    std::fs::write(out, code).unwrap();
}

/// Groups that can be compiled out with a cargo feature.
fn feature_for(group: &str) -> Option<&'static str> {
    match group {
        "youtube" => Some("youtube"),
        _ => None,
    }
}
